-- ═══════════════════════════════════════════════════════════════════════
--  CHIDORI · Mantenimiento · PASO 6 · Exportar el esquema (SOLO LECTURA)
--
--  Genera, como filas de texto, las sentencias SQL que reconstruyen la
--  ESTRUCTURA de la base: tablas, restricciones, índices, funciones, vistas,
--  triggers, RLS, políticas, permisos y comentarios. No exporta datos, ni
--  contraseñas, ni usuarios: solo la forma de la base.
--
--  No modifica nada de la base. Crea dos vistas y una función TEMPORALES
--  (en pg_temp: desaparecen solas al terminar) para poder correr cada parte
--  por separado: si una falla, en vez de cortar todo devuelve una fila
--  "ERROR" con el motivo y sigue con las demás.
--
--  Cómo correrlo: SQL Editor → pegar → Run → "Download CSV" (o Export →
--  CSV) y pasarle el archivo a Claude, que arma con eso sql/esquema_base.sql.
--  OJO: no copiar la tabla de pantalla, porque las funciones y vistas tienen
--  varias líneas y se rompen. Tiene que ser el CSV.
--
--  Quedan afuera a propósito: el esquema `respaldo` y las tablas
--  bkp_20260904_* (son copias, no parte del diseño).
-- ═══════════════════════════════════════════════════════════════════════

create or replace temp view tablas as
select c.oid, c.relname
    from pg_class c
    join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and c.relkind in ('r', 'p')
     and c.relname not like 'bkp\_%';

create or replace temp view vistas as
select c.oid, c.relname, c.reloptions
    from pg_class c
    join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and c.relkind = 'v';

create or replace function pg_temp.exportar_esquema()
returns table (orden int, seccion text, objeto text, sentencia text)
language plpgsql as $fn$
declare
  partes text[] := array[
    $q$
select 0 as orden, '00 encabezado' as seccion, ''::text as objeto,
         'set check_function_bodies = false;' as sentencia
    $q$,
    $q$
select 10, '10 secuencia', s.relname::text,
         format('create sequence if not exists public.%I;', s.relname)
    from pg_class s
    join pg_namespace n on n.oid = s.relnamespace
   where n.nspname = 'public' and s.relkind = 'S'
     and not exists (select 1 from pg_depend d where d.objid = s.oid and d.deptype = 'i')   -- no las de identity
    $q$,
    $q$
select 20, '20 tabla', t.relname::text,
         format(E'create table if not exists public.%I (\n%s\n);', t.relname,
           (select string_agg(
                     format('  %I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
                            case a.attidentity when 'a' then ' generated always as identity'
                                               when 'd' then ' generated by default as identity' else '' end,
                            case when ad.adbin is not null and a.attidentity = '' then ' default ' || pg_get_expr(ad.adbin, ad.adrelid) else '' end,
                            case when a.attnotnull then ' not null' else '' end),
                     E',\n' order by a.attnum)
              from pg_attribute a
              left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
             where a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped))
    from tablas t
    $q$,
    $q$
select case when con.contype = 'f' then 31 else 30 end,
         case when con.contype = 'f' then '31 clave foránea' else '30 restricción' end,
         (t.relname || ' · ' || con.conname)::text,
         format('alter table public.%I add constraint %I %s;', t.relname, con.conname, pg_get_constraintdef(con.oid))
    from pg_constraint con
    join tablas t on t.oid = con.conrelid
   where con.contype in ('p', 'u', 'c', 'f')
    $q$,
    $q$
select 32, '32 secuencia de columna', s.relname::text,
         format('alter sequence public.%I owned by public.%I.%I;', s.relname, t.relname, a.attname)
    from pg_class s
    join pg_depend d on d.objid = s.oid and d.deptype = 'a' and d.classid = 'pg_class'::regclass
    join tablas t on t.oid = d.refobjid
    join pg_attribute a on a.attrelid = t.oid and a.attnum = d.refobjsubid
   where s.relkind = 'S'
    $q$,
    $q$
select 40, '40 índice', i.relname::text, pg_get_indexdef(i.oid) || ';'
    from pg_index x
    join pg_class i on i.oid = x.indexrelid
    join tablas t on t.oid = x.indrelid
   where not exists (select 1 from pg_constraint con where con.conindid = x.indexrelid)
    $q$,
    $q$
select 50, '50 función', p.proname::text, pg_get_functiondef(p.oid) || ';'
    from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'public' and p.prokind = 'f'
    $q$,
    $q$
select 60, '60 vista', v.relname::text,
         format(E'create or replace view public.%I%s as\n%s', v.relname,
                coalesce(' with (' || array_to_string(v.reloptions, ', ') || ')', ''),
                pg_get_viewdef(v.oid, true))
    from vistas v
    $q$,
    $q$
select 70, '70 trigger', (c.relname || ' · ' || tg.tgname)::text, pg_get_triggerdef(tg.oid) || ';'
    from pg_trigger tg
    join pg_class c on c.oid = tg.tgrelid
    join pg_namespace n on n.oid = c.relnamespace
   where not tg.tgisinternal
     and (c.oid in (select oid from tablas) or (n.nspname = 'auth' and c.relname = 'users'))
    $q$,
    $q$
select 80, '80 rls', t.relname::text, format('alter table public.%I enable row level security;', t.relname)
    from tablas t
    join pg_class c on c.oid = t.oid
   where c.relrowsecurity
    $q$,
    $q$
select 81, '81 política', (p.tablename || ' · ' || p.policyname)::text,
         format('create policy %I on public.%I as %s for %s to %s%s%s;',
                p.policyname, p.tablename, lower(p.permissive), p.cmd,
                array_to_string(p.roles, ', '),
                coalesce(E'\n  using (' || p.qual || ')', ''),
                coalesce(E'\n  with check (' || p.with_check || ')', ''))
    from pg_policies p
   where p.schemaname = 'public' and p.tablename not like 'bkp\_%'
    $q$,
    $q$
select 90, '90 permiso', r.relname::text,
         format('revoke all on public.%I from anon, authenticated;', r.relname)
         || coalesce((select string_agg(format(E'\ngrant %s on public.%I to %I;',
                                               lower(g.privs), r.relname, g.grantee), '' order by g.grantee)
                        from (select grantee, string_agg(privilege_type, ', ' order by privilege_type) as privs
                                from information_schema.role_table_grants
                               where table_schema = 'public' and table_name = r.relname
                                 and grantee in ('anon', 'authenticated')
                               group by grantee) g), '')
    from (select relname from tablas union all select relname from vistas) r
    $q$,
    $q$
select 91, '91 permiso función', p.proname::text,
         format('revoke all on function public.%I(%s) from anon, authenticated;',
                p.proname, pg_get_function_identity_arguments(p.oid))
         || case when has_function_privilege('anon', p.oid, 'execute')
                 then format(E'\ngrant execute on function public.%I(%s) to anon;', p.proname, pg_get_function_identity_arguments(p.oid)) else '' end
         || case when has_function_privilege('authenticated', p.oid, 'execute')
                 then format(E'\ngrant execute on function public.%I(%s) to authenticated;', p.proname, pg_get_function_identity_arguments(p.oid)) else '' end
    from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'public' and p.prokind = 'f'
    $q$,
    $q$
select 95, '95 comentario', c.relname::text,
         format('comment on %s public.%I is %L;', case c.relkind when 'v' then 'view' else 'table' end,
                c.relname, obj_description(c.oid, 'pg_class'))
    from pg_class c
   where c.oid in (select oid from tablas union all select oid from vistas)
     and obj_description(c.oid, 'pg_class') is not null
    $q$,
    $q$
select 96, '95 comentario', (c.relname || '.' || a.attname)::text,
         format('comment on column public.%I.%I is %L;', c.relname, a.attname, col_description(c.oid, a.attnum))
    from pg_class c
    join pg_attribute a on a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped
   where c.oid in (select oid from tablas union all select oid from vistas)
     and col_description(c.oid, a.attnum) is not null
    $q$
  ];
  i int;
begin
  for i in 1 .. array_length(partes, 1) loop
    begin
      return query execute partes[i];
    exception when others then
      return query select 999, 'ERROR en la parte ' || i, sqlstate::text, sqlerrm::text;
    end;
  end loop;
end
$fn$;

select * from pg_temp.exportar_esquema()
 order by orden, objeto;
